-- Chạy bằng: npm run db:setup  (an toàn khi chạy lại nhiều lần)
-- Ngày giờ lưu dạng TEXT 'YYYY-MM-DD HH:MM:SS' (giờ UTC) để giữ nguyên định dạng của phiên bản SQLite.
