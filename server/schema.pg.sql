-- Băm mật khẩu bằng bcrypt ngay trong CSDL (Worker gói miễn phí không đủ CPU để băm)
CREATE EXTENSION IF NOT EXISTS pgcrypto;
-- Tìm kiếm tiếng Việt không dấu ("tra" khớp "Trà", "dong" khớp "đông")
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE OR REPLACE FUNCTION sbtt_norm(t text) RETURNS text
LANGUAGE sql STABLE SET search_path = public, extensions AS $$
  SELECT lower(unaccent(replace(replace(coalesce(t, ''), 'đ', 'd'), 'Đ', 'D')))
$$;

-- Hàm tương thích cú pháp SQLite: datetime('now'), datetime('now', '+14 days'), datetime('now','-10 minutes')
CREATE OR REPLACE FUNCTION datetime(t text, modifier text DEFAULT NULL) RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT to_char(
    (CASE WHEN t = 'now' THEN (now() AT TIME ZONE 'UTC') ELSE t::timestamp END) + COALESCE(modifier::interval, interval '0'),
    'YYYY-MM-DD HH24:MI:SS')
$$;

CREATE OR REPLACE FUNCTION sbtt_hash_password(pw text) RETURNS text
LANGUAGE sql VOLATILE SET search_path = public, extensions AS $$
  SELECT crypt(pw, gen_salt('bf', 10))
$$;

CREATE OR REPLACE FUNCTION sbtt_check_password(pw text, stored text) RETURNS boolean
LANGUAGE sql STABLE SET search_path = public, extensions AS $$
  SELECT stored IS NOT NULL AND stored LIKE '$2%' AND crypt(pw, stored) = stored
$$;

-- Địa điểm: văn phòng, kho tổng, kho IT, kho hành chính, 37 cửa hàng
CREATE TABLE IF NOT EXISTS locations (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL,
  type          TEXT NOT NULL CHECK (type IN ('office','warehouse','warehouse_it','warehouse_admin','store')),
  address       TEXT,
  region        TEXT,
  phone         TEXT,
  manager_user_id INTEGER,
  active        INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL DEFAULT datetime('now')
);

-- Danh mục quyền (thao tác nghiệp vụ)
CREATE TABLE IF NOT EXISTS permissions (
  code    TEXT PRIMARY KEY,
  module  TEXT NOT NULL,
  name    TEXT NOT NULL,
  sort    INTEGER NOT NULL DEFAULT 0
);

-- Chức danh / vị trí công việc (vai trò)
CREATE TABLE IF NOT EXISTS roles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  department  TEXT,
  description TEXT,
  all_locations INTEGER NOT NULL DEFAULT 0,
  is_system   INTEGER NOT NULL DEFAULT 0,
  created_at  TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE IF NOT EXISTS role_permissions (
  role_id         INTEGER NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_code TEXT NOT NULL REFERENCES permissions(code) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_code)
);

CREATE TABLE IF NOT EXISTS users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_code   TEXT UNIQUE,
  full_name       TEXT NOT NULL,
  email           TEXT UNIQUE,          -- luôn lưu chữ thường
  phone           TEXT UNIQUE,
  password_hash   TEXT,
  role_id         INTEGER NOT NULL REFERENCES roles(id),
  department      TEXT,
  all_locations   INTEGER NOT NULL DEFAULT 0,
  status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','locked')),
  must_change_password INTEGER NOT NULL DEFAULT 1,
  google_sub      TEXT UNIQUE,
  last_login_at   TEXT,
  created_at      TEXT NOT NULL DEFAULT datetime('now'),
  updated_at      TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

DO $$ BEGIN
  ALTER TABLE locations ADD CONSTRAINT locations_manager_fk FOREIGN KEY (manager_user_id) REFERENCES users(id);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS user_locations (
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  location_id INTEGER NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, location_id)
);

CREATE TABLE IF NOT EXISTS user_permission_overrides (
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  permission_code TEXT NOT NULL REFERENCES permissions(code) ON DELETE CASCADE,
  effect          TEXT NOT NULL CHECK (effect IN ('grant','deny')),
  PRIMARY KEY (user_id, permission_code)
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash  TEXT PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  TEXT NOT NULL DEFAULT datetime('now'),
  expires_at  TEXT NOT NULL,
  ip          TEXT,
  user_agent  TEXT,
  method      TEXT
);
CREATE INDEX IF NOT EXISTS ix_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS otp_codes (
  phone       TEXT PRIMARY KEY,
  code_hash   TEXT NOT NULL,
  expires_at  TEXT NOT NULL,
  attempts    INTEGER NOT NULL DEFAULT 0,
  created_at  TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE IF NOT EXISTS asset_categories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  grp         TEXT NOT NULL,
  maintenance_cycle_days INTEGER,
  useful_life_months     INTEGER,
  label_qr    INTEGER NOT NULL DEFAULT 1,
  active      INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS assets (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_code        TEXT NOT NULL UNIQUE,
  qr_token          TEXT NOT NULL UNIQUE,
  name              TEXT NOT NULL,
  category_id       INTEGER NOT NULL REFERENCES asset_categories(id),
  location_id       INTEGER NOT NULL REFERENCES locations(id),
  area              TEXT,
  custodian_user_id INTEGER REFERENCES users(id),
  brand             TEXT,
  model             TEXT,
  serial_no         TEXT,
  specs             TEXT,
  status            TEXT NOT NULL DEFAULT 'in_use'
                    CHECK (status IN ('in_use','in_storage','under_repair','broken','liquidated','lost')),
  criticality       TEXT NOT NULL DEFAULT 'B' CHECK (criticality IN ('A','B','C')),
  accounting_code   TEXT,
  accounting_type   TEXT CHECK (accounting_type IN ('TSCD','CCDC','KHAC')),
  accounting_account TEXT,
  cost_center       TEXT,
  purchase_date     TEXT,
  in_service_date   TEXT,
  original_cost     DOUBLE PRECISION,
  useful_life_months INTEGER,
  supplier          TEXT,
  invoice_no        TEXT,
  warranty_until    TEXT,
  warranty_provider TEXT,
  warranty_contact  TEXT,
  maintenance_cycle_days INTEGER,
  maintenance_vendor TEXT,
  last_maintenance_date TEXT,
  next_maintenance_date TEXT,
  notes             TEXT,
  created_by        INTEGER REFERENCES users(id),
  created_at        TEXT NOT NULL DEFAULT datetime('now'),
  updated_at        TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS ix_assets_location ON assets(location_id);
CREATE INDEX IF NOT EXISTS ix_assets_category ON assets(category_id);
CREATE INDEX IF NOT EXISTS ix_assets_next_mt ON assets(next_maintenance_date);

CREATE TABLE IF NOT EXISTS incidents (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id      INTEGER NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  title         TEXT NOT NULL,
  description   TEXT,
  severity      TEXT NOT NULL DEFAULT 'normal' CHECK (severity IN ('low','normal','high','critical')),
  status        TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','resolved','cancelled')),
  reported_by   INTEGER REFERENCES users(id),
  assigned_to   INTEGER REFERENCES users(id),
  resolution    TEXT,
  created_at    TEXT NOT NULL DEFAULT datetime('now'),
  resolved_at   TEXT
);
CREATE INDEX IF NOT EXISTS ix_inc_asset ON incidents(asset_id);

CREATE TABLE IF NOT EXISTS maintenance_records (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id      INTEGER NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  type          TEXT NOT NULL CHECK (type IN ('preventive','corrective','inspection','warranty')),
  performed_date TEXT NOT NULL,
  performed_by  TEXT,
  vendor        TEXT,
  description   TEXT NOT NULL,
  result        TEXT,
  cost          DOUBLE PRECISION DEFAULT 0,
  ticket_ref    TEXT,
  incident_id   INTEGER REFERENCES incidents(id) ON DELETE SET NULL,
  created_by    INTEGER REFERENCES users(id),
  created_at    TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS ix_mt_asset ON maintenance_records(asset_id);

CREATE TABLE IF NOT EXISTS transfers (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id         INTEGER NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  from_location_id INTEGER NOT NULL REFERENCES locations(id),
  to_location_id   INTEGER NOT NULL REFERENCES locations(id),
  from_custodian_id INTEGER REFERENCES users(id),
  to_custodian_id  INTEGER REFERENCES users(id),
  reason           TEXT,
  status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
  requested_by     INTEGER REFERENCES users(id),
  decided_by       INTEGER REFERENCES users(id),
  decision_note    TEXT,
  created_at       TEXT NOT NULL DEFAULT datetime('now'),
  decided_at       TEXT
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  action     TEXT NOT NULL,
  entity     TEXT,
  entity_id  INTEGER,
  detail     TEXT,
  ip         TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS ix_audit_entity ON audit_logs(entity, entity_id);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);

-- Giới hạn số lần thử (đăng nhập, OTP) dùng chung cho mọi Worker/tiến trình
CREATE TABLE IF NOT EXISTS rate_limits (
  key       TEXT PRIMARY KEY,
  n         INTEGER NOT NULL,
  reset_at  TEXT NOT NULL
);

-- Supabase: chặn truy cập trực tiếp qua API REST công khai (ứng dụng kết nối bằng tài khoản postgres qua Hyperdrive)
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['locations','permissions','roles','role_permissions','users','user_locations','user_permission_overrides',
    'sessions','otp_codes','asset_categories','assets','incidents','maintenance_records','transfers','audit_logs','settings','rate_limits'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- Supabase: không cho gọi các hàm của ứng dụng qua API công khai (PostgREST /rpc) bằng khoá anon/authenticated
DO $$
DECLARE f text; r text;
BEGIN
  FOREACH f IN ARRAY ARRAY['datetime(text, text)', 'sbtt_hash_password(text)', 'sbtt_check_password(text, text)', 'sbtt_norm(text)'] LOOP
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC', f);
    FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM %I', f, r); END IF;
    END LOOP;
  END LOOP;
END $$;
